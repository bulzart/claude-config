"""text_overlays.py — edit-plan.json text_overlays -> overlays.ass (hook text, callouts, end cards).

    python text_overlays.py <edit-plan.json> [--out overlays.ass] [--fonts-dir DIR] [--max-overlays 12] [--json]

OWNER RULE (hard-wired): this script never produces speech captions or subtitles.
  * It has NO transcript input. The flags --transcript / --srt / --words / --from-transcript /
    --whisper are recognised only to refuse them (exit 3) so nobody can wire a caption generator here.
  * A plan with a captions/subtitles block, an overlay of type caption/subtitle/speech, an overlay with
    words[]/word_timestamps/transcript keys, or a caption-like density of short back-to-back overlays
    is refused (exit 3).
Allowed overlay types: hook_text | callout | end_card | sticker (text stickers; PNG stickers are
composited by render_ffmpeg.py and are ignored here).

Layout: every block is anchored inside the safe box (plan.project.safe_zones or the universal box
x 65-915 / y 270-1248 at 1080x1920 from references\\post-generation-playbook.md 4.3) with \\an5\\pos(x,y).
Fonts: tools\\edit\\fonts (Montserrat ExtraBold/Black/Bold, Anton, Bebas Neue) through libass fontsdir;
fallbacks Arial Black -> Impact (system). Style presets: hook-v1, callout-v1, endcard-v1, sticker-text-v1.

Exit codes: 0 ok, 1 usage/plan error, 3 refused (caption-shaped input).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common_edit as ce  # noqa: E402

POISON_FLAGS = ("--transcript", "--srt", "--words", "--from-transcript", "--whisper", "--subtitles", "--captions")


def ass_colour(hex_rgb: str, alpha: int = 0) -> str:
    """#RRGGBB -> &HAABBGGRR (ASS is BGR)."""
    h = hex_rgb.lstrip("#")
    if len(h) != 6:
        h = "FFFFFF"
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{alpha:02X}{b}{g}{r}".upper()


def ass_time(t: float) -> str:
    t = max(0.0, float(t))
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def ass_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}")


def style_line(name: str, preset: dict, font: str, size: int) -> str:
    bold = -1 if preset.get("bold") else 0
    return ("Style: {name},{font},{size},{primary},{secondary},{outline_c},{back},{bold},0,0,0,100,100,0,0,1,"
            "{outline},{shadow},5,0,0,0,1").format(
        name=name, font=font, size=size, primary=ass_colour(preset.get("fill", "#FFFFFF")),
        secondary=ass_colour("#FFE600"), outline_c=ass_colour(preset.get("outline_colour", "#000000")),
        back=ass_colour("#000000", 0x80), bold=bold, outline=int(preset.get("outline", 4)),
        shadow=int(preset.get("shadow", 0)))


def event_text(item: dict) -> str:
    preset = item["preset"]
    fade = preset.get("fade") or (0, 0)
    tags = f"\\an5\\pos({item['x']:.0f},{item['y']:.0f})"
    if fade and (fade[0] or fade[1]):
        tags += f"\\fad({int(fade[0])},{int(fade[1])})"
    hl = {w.lower().strip(".,!?") for w in item.get("highlight_words") or []}
    hl_col = ass_colour(item.get("highlight_colour") or "#FFE600").replace("&H00", "&H")
    primary = ass_colour(preset.get("fill", "#FFFFFF")).replace("&H00", "&H")
    lines_out = []
    for li, line in enumerate(item["lines"]):
        words = []
        for w in line.split(" "):
            core = w.lower().strip(".,!?")
            if hl and core in hl:
                words.append(f"{{\\c{hl_col}&}}{ass_escape(w)}{{\\c{primary}&}}")
            else:
                words.append(ass_escape(w))
        txt = " ".join(words)
        if li > 0 and item["type"] == "end_card" and preset.get("sub_font"):
            sub_family, _ = ce.resolve_font(preset["sub_font"], item.get("_fonts_dir", ce.FONTS_DIR))
            txt = f"{{\\fn{sub_family}\\fs{int(preset.get('sub_size', 60))}\\bord4}}{txt}"
        lines_out.append(txt)
    return "{" + tags + "}" + "\\N".join(lines_out)


def build_ass(plan: dict, fonts_dir: str, total_duration: float | None = None, max_overlays: int = 12) -> tuple[str, list[dict]]:
    items = ce.layout_overlays(plan, fonts_dir=fonts_dir, total_duration=total_duration)
    guard = ce.caption_density_guard(items, max_overlays=max_overlays)
    if guard:
        raise ce.PlanError(guard)
    W, H = int(plan["project"]["width"]), int(plan["project"]["height"])
    styles = {}
    for it in items:
        it["_fonts_dir"] = fonts_dir
        key = (it["style"], it["font"], it["size"])
        styles.setdefault(key, f"{it['style']}-{it['font'].replace(' ', '')}-{it['size']}")
        it["ass_style"] = styles[key]
    box = ce.safe_box_for(plan)
    head = [
        "[Script Info]",
        "; overlays.ass generated by tools\\edit\\text_overlays.py — hook text / callouts / end cards ONLY.",
        "; Speech captions/subtitles are never written here (owner rule); the owner captions with a separate tool.",
        f"; Safe box used: x {box['x_min']}-{box['x_max']}, y {box['y_min']}-{box['y_max']} (px at {W}x{H}).",
        "ScriptType: v4.00+",
        f"PlayResX: {W}",
        f"PlayResY: {H}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, "
        "Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, "
        "MarginR, MarginV, Encoding",
    ]
    seen = set()
    for it in items:
        if it["ass_style"] in seen:
            continue
        seen.add(it["ass_style"])
        head.append(style_line(it["ass_style"], it["preset"], it["font"], it["size"]))
    head += ["", "[Events]", "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"]
    for it in sorted(items, key=lambda o: o["t_start"]):
        head.append(f"Dialogue: 0,{ass_time(it['t_start'])},{ass_time(it['t_end'])},{it['ass_style']},{it['id']},0,0,0,,"
                    f"{event_text(it)}")
    for it in items:
        it.pop("_fonts_dir", None)
        it.pop("preset", None)
    return "\n".join(head) + "\n", items


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    for a in argv:
        if a.split("=")[0] in POISON_FLAGS:
            print(f"REFUSED: {a} — text_overlays.py never takes transcript/caption input (owner rule: speech captions "
                  f"are added afterwards with a separate tool).", file=sys.stderr)
            return 3
    ap = argparse.ArgumentParser(description="edit-plan text_overlays -> overlays.ass (never captions)")
    ap.add_argument("plan", help="absolute path to edit-plan.json")
    ap.add_argument("--out", help="output .ass (default: <plan dir>\\overlays.ass)")
    ap.add_argument("--fonts-dir", default=ce.FONTS_DIR)
    ap.add_argument("--max-overlays", type=int, default=12)
    ap.add_argument("--total-duration", type=float, default=None, help="clamp overlays to this length (s)")
    ap.add_argument("--json", action="store_true", help="print the resolved layout as JSON")
    args = ap.parse_args(argv)
    try:
        plan, base = ce.load_plan(args.plan)
    except ce.PlanError as e:
        print(f"REFUSED/INVALID: {e}", file=sys.stderr)
        return 3 if ("owner rule" in str(e) or "refused" in str(e).lower()) else 1
    total = args.total_duration
    if total is None:
        try:
            _, total = ce.compute_timeline(plan)
        except Exception:
            total = None
    try:
        ass, items = build_ass(plan, args.fonts_dir, total_duration=total, max_overlays=args.max_overlays)
    except ce.PlanError as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 3
    out = args.out or ce.default_overlays_path(args.plan)
    ce.write_text(out, ass)
    sidecar = os.path.splitext(out)[0] + ".layout.json"
    ce.save_json(sidecar, {"generated": ce.now_iso(), "plan": os.path.abspath(args.plan), "ass": os.path.abspath(out),
                           "fonts_dir": os.path.abspath(args.fonts_dir), "overlays": items})
    summary = {"ass": os.path.abspath(out), "layout": sidecar, "count": len(items),
               "fonts": sorted({(i["font"], i["font_path"] or "system") for i in items}),
               "outside_safe_box": [i["id"] for i in items if not i["in_safe_box"]],
               "warnings": {i["id"]: i["warnings"] for i in items if i["warnings"]}}
    print(json.dumps(summary, ensure_ascii=False, indent=2 if args.json else None, default=list))
    return 0


if __name__ == "__main__":
    sys.exit(main())
